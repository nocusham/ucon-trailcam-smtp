"""Explicit historical SMTP dispatch from a new private export, under queue lock."""
import json
import time
from pathlib import Path

from ucon_trailcam_smtp.history_download import read_original
from ucon_trailcam_smtp.history_receipts import camera_uncertain, reserve, finish, rollback_unsent
from ucon_trailcam_smtp.queue_smtp import prepare, message_batches, validate_destination
from ucon_trailcam_smtp.mail_message import build_message
from ucon_trailcam_smtp.cloud_image import MAX_IMAGE_BYTES
from ucon_trailcam_smtp.smtp_transport import SafeSMTPFailure, smtp_failure_fields
from ucon_trailcam_smtp.smtp_retry import retry_due, record_setup_failure, clear_retry
from ucon_trailcam_smtp.safe_diagnostics import error_fields


def eligible(state,resend=False,allow_unknown=False):
    if state in ('sent','sent_history'):
        return resend
    if state=='unknown_history':
        return allow_unknown
    return state in ('pending','downloaded','expired')


def preflight(db,profile,secrets,*,now=None):
    if not profile.enabled:
        raise ValueError('Camera disabled')
    if camera_uncertain(db,profile.uid) or db.execute(
            "SELECT 1 FROM events WHERE camera_uid=? AND state='uncertain' LIMIT 1",(profile.uid,)).fetchone():
        raise ValueError('Camera has unresolved SMTP outcome')
    if not retry_due(db,profile.uid,int(time.time()) if now is None else now):
        raise ValueError('SMTP camera cooldown active')
    validate_destination(profile.mode,profile.host,profile.recipient)
    password = profile.password or secrets.get(profile.password_env) if profile.username else None
    if profile.username and not password:
        raise ValueError('Missing configured SMTP password')
    return password


def records_from_export(root,uid,*,resend=False,allow_unknown=False):
    # Only the export generated by the current invocation is accepted.
    # Do not offer a CLI that imports an arbitrary manifest.
    root=Path(root)
    records=[]
    seen=set()
    with (root/'manifest.jsonl').open(encoding='utf-8') as source:
        for line in source:
            rec=json.loads(line)
            if rec['camera_uid']!=uid or rec['itemid'] in seen or not eligible(rec['prior_state'],resend,allow_unknown):
                raise ValueError('Unexpected historical export selection')
            rel=Path(rec['file'])
            if rel.is_absolute() or '..' in rel.parts or len(rel.parts)!=2:
                raise ValueError('Unexpected historical export path')
            path=root/rel
            if path.resolve()!=path or not path.is_relative_to(root):
                raise ValueError('Unsafe historical export path')
            rec['path']=str(path)
            seen.add(rec['itemid'])
            records.append(rec)
    return sorted(records,key=lambda r:(r['et_utc'],r['itemid']))


def safe_load(path):
    data,(_,_,w,h)=read_original(path)
    if len(data)>MAX_IMAGE_BYTES:
        raise ValueError('Original exceeds SMTP image size limit')
    return data,'jpg',w,h,path.name


def send_export(db,profile,root,pacer,send,*,resend=False,allow_unknown=False,
                sleep=time.sleep,now=lambda:int(time.time()),emit=print):
    records=records_from_export(root,profile.uid,resend=resend,allow_unknown=allow_unknown)
    # Verify the full requested export before the first attempt. Reverify
    # each actual message at preparation, retaining only one group in memory.
    def row(rec):
        return (rec['camera_uid'],rec['itemid'],rec['et_utc'],
                json.dumps(rec['metadata'],ensure_ascii=False,allow_nan=False),
                rec['sd_time'],rec['path'],rec['sha256'],rec['size'],rec['width'],rec['height'])
    def prepared(rec):
        r=row(rec)
        return r,prepare(r,safe_load,build_message,profile.sender,profile.recipient,camera_name=profile.name)
    for rec in records:
        prepared(rec)
    if profile.security=='none':
        emit('WARNING: unencrypted SMTP explicitly configured for this camera')
    if allow_unknown:
        emit('WARNING: unknown delivery history explicitly allowed; duplicates are possible.')
    group_size=profile.limit if profile.mode=='grouped' else 1
    for start in range(0,len(records),group_size):
        group=records[start:start+group_size]
        if camera_uncertain(db,profile.uid) or db.execute(
                "SELECT 1 FROM events WHERE camera_uid=? AND state='uncertain' LIMIT 1",(profile.uid,)).fetchone():
            emit('Historical SMTP blocked by uncertain delivery.')
            return 1
        if not retry_due(db,profile.uid,now()):
            emit('Historical SMTP camera cooldown active.')
            return 1
        (_,msg),=message_batches([prepared(rec) for rec in group],profile.mode,camera_name=profile.name)
        # The service is stopped and the shared queue lock is held. Poll
        # the persisted gate without consuming a slot until actually ready.
        while not pacer.reserve():
            sleep(1)
        message_id=str(msg['Message-ID'])
        reserve(db,profile.uid,group,message_id,now(),profile.route(),resend=resend,allow_unknown=allow_unknown)
        try:
            send(msg)
        except SafeSMTPFailure as exc:
            rollback_unsent(db,profile.uid,message_id,len(group))
            delay=record_setup_failure(db,profile.uid,now())
            emit(f'Historical SMTP setup failed before submission; {smtp_failure_fields(exc)}; cooldown={delay}s.')
            return 1
        except (Exception,KeyboardInterrupt) as exc:
            emit(f'Historical SMTP outcome uncertain; {smtp_failure_fields(exc)}. Check inbox before resolution.')
            return 1
        try:
            finish(db,profile.uid,message_id,now(),len(group))
        except (Exception,KeyboardInterrupt) as exc:
            emit(f'Historical SMTP acceptance not committed; {error_fields(exc)}. Check inbox before resolution.')
            return 1
        clear_retry(db,profile.uid)
        emit(f'Historical SMTP accepted: images={len(group)}.')
    return 0
